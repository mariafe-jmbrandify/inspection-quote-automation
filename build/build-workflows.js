function applyLayout(wf) {
  for (const n of wf.nodes) {
    const l = LAYOUT[n.name];
    if (!l) throw new Error('No layout for ' + n.name);
    n.position = [Math.round(l[0] * 240), l[1]];
    if (n.type === 'n8n-nodes-base.stickyNote') {
      n.parameters.width = Math.round(l[2] * 240);
      n.parameters.height = l[3];
    }
  }
}

