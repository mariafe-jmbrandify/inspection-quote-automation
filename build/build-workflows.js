// Deterministic UUIDs so rebuilding does not create noisy git diffs.
function uuid(seed) {
  const h = crypto.createHash('sha1').update(seed).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

function lib(file) {
  const src = fs.readFileSync(path.join(ROOT, 'src', file), 'utf8');
  const i = src.indexOf(EXPORT_MARKER);
  if (i === -1) throw new Error(`${file} is missing the export marker`);
  return src.slice(0, i).trim();
}

function codeNode(name, libs, glue, pos) {
  const header = `// GENERATED by build/build-workflows.js from src/${libs.join(', src/')}. Edit those files, not this node.\n\n`;
  return {
    name,
    type: 'n8n-nodes-base.code',
    typeVersion: 2,
    position: pos,
    parameters: { jsCode: header + libs.map(lib).join('\n\n') + '\n\n// ---- node glue ----\n' + glue.trim() + '\n' },
  };
}

function ifNode(name, leftValue, operator, rightValue, pos) {
  return {
    name,
    type: 'n8n-nodes-base.if',
    typeVersion: 2.2,
    position: pos,
    parameters: {
      conditions: {
        options: { caseSensitive: true, leftValue: '', typeValidation: 'strict', version: 2 },
        conditions: [{ id: uuid(name + 'cond'), leftValue, rightValue: rightValue ?? '', operator }],
        combinator: 'and',
      },
      options: {},
    },
  };
}
const isTrue = { type: 'boolean', operation: 'true', singleValue: true };
const strEq = { type: 'string', operation: 'equals' };

function respondNode(name, statusCode, bodyExpr, pos) {
  return {
    name,
    type: 'n8n-nodes-base.respondToWebhook',
    typeVersion: 1.1,
    position: pos,
    parameters: { respondWith: 'json', responseBody: bodyExpr, options: { responseCode: statusCode } },
  };
}

function notifyNode(name, pos) {
  return {
    name,
    type: 'n8n-nodes-base.httpRequest',
    typeVersion: 4.2,
    position: pos,
    retryOnFail: true,
    maxTries: 3,
    waitBetweenTries: 3000,
    parameters: {
      method: 'POST',
      url: '={{ $json.notifyUrl }}',
      sendBody: true,
      specifyBody: 'json',
      jsonBody: '={{ JSON.stringify($json.payload) }}',
      options: { timeout: 15000 },
    },
  };
}

function sticky(name, content, pos, width, height, color) {
  return {
    name,
    type: 'n8n-nodes-base.stickyNote',
    typeVersion: 1,
    position: pos,
    parameters: { content, width, height, color },
  };
}

function webhook(name, method, pathName, responseMode, pos) {
  return {
    name,
    type: 'n8n-nodes-base.webhook',
    typeVersion: 2,
    position: pos,
    webhookId: uuid('webhook:' + pathName + method),
    parameters: { httpMethod: method, path: pathName, responseMode, options: {} },
  };
}

function finalize(workflow) {
  workflow.nodes.forEach((n) => {
    n.id = uuid(workflow.id + ':' + n.name);
  });
  const names = new Set(workflow.nodes.map((n) => n.name));
  if (names.size !== workflow.nodes.length) throw new Error('Duplicate node names in ' + workflow.name);
  const connections = {};
  for (const [from, outputs] of workflow.edges) {
    if (!names.has(from)) throw new Error(`Unknown node in edges: ${from}`);
    connections[from] = {
      main: outputs.map((targets) =>
        (targets || []).map((to) => {
          if (!names.has(to)) throw new Error(`Unknown node in edges: ${to}`);
          return { node: to, type: 'main', index: 0 };
        })
      ),
    };
  }
  const { edges, ...rest } = workflow;
  return { ...rest, connections, pinData: {}, active: false };
}

