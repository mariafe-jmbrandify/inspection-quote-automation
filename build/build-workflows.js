/**
 * Builds the importable n8n workflow JSON files in /workflows from the
 * JavaScript in /src.
 *
 * Why: n8n Code nodes cannot import local files, and code edited inside the
 * n8n UI is hard to review or test. So the real logic lives in /src (tested
 * with `npm test`), and this script copies it into each Code node.
 *
 *   npm run build      -> regenerates workflows/*.json
 *
 * Never edit Code node JavaScript in the n8n UI and forget to copy it back:
 * the next build overwrites it.
 */
